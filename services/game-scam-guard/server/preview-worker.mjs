import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {renderIsolatedSnapshot} from './preview-renderer.mjs';
for(const key of ['ABUSECH_AUTH_KEY','MALWAREBAZAAR_AUTH_KEY','MALGUARD_ABUSECH_AUTH_KEY','GUARD_REPORT_SECRET','VERCEL_OIDC_TOKEN','VERCEL_TOKEN','BREVO_API_KEY','SUPABASE_SERVICE_ROLE_KEY'])if(process.env[key])throw new Error('Unexpected credential in isolated renderer');
process.env.PLAYWRIGHT_BROWSERS_PATH||='/vercel/sandbox/browsers';
const {chromium}=await import('/vercel/sandbox/node_modules/playwright/index.mjs');
const job=JSON.parse(await readFile(process.argv[2],'utf8'));
const result=await renderIsolatedSnapshot({chromium,url:job.url,html:job.html});
await mkdir('/tmp/guard-preview-output',{recursive:true});
await writeFile('/tmp/guard-preview-output/preview.jpg',result.jpeg);
await writeFile('/tmp/guard-preview-output/preview-check.json',JSON.stringify(result.telemetry));
